def solution(A):
    n = len(A)

    # add up every number from 1 to n + 1 (the total if nothing was missing)
    # range stops before its end value, so it has to go to n + 2
    expected_total = 0
    for number in range(1, n + 2):
        expected_total += number

    #add up the numbers that are actually in the list
    actual_total = sum(A)

    # whatever is left over is missing number
    return expected_total - actual_total