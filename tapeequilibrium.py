def solution(A):
    # add up the whole tape once
    total = sum(A)
    left_sum = 0
    differences = []

    # try every split point, stopping early so the right side
    # always keeps at least on number
    for i in range(len(A) - 1):
        # move one number from the right side to the left side
        left_sum += A[i]
        right_sum = total - left_sum
        difference = left_sum - right_sum

        # absolute value: turn a negative difference positive
        if difference < 0:
            difference = difference * -1

        differences.append(difference)

    # the answer is the smallest difference we found
    return min(differences)