def solution(X, Y, D):
    # how far the frog still has to go
    distance = Y - X

    # how many full jumps fit in that distance
    jumps = distance // D

    # if there is distance left over, the frog needs on more jump
    if distance % D != 0:
        jumps+= 1

    return jumps