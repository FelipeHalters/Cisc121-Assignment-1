def solution(A):
    # dictionary to count how many times each number shows up
    counts = {}

    for number in A:
        if number in counts:
            # seen it before, add on to its count
            counts[number] += 1
        else:
            # first time seeing it, start its count at 1
            counts[number] = 1

    # the unpaired number is the one that shows up an odd number
    for number in counts:
        if counts[number] % 2 != 0:
            return number