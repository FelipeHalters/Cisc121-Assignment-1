def solution(A, K):
    # if the list is empty there is nothing to rotate
    if len(A) == 0:
        return A

    # do one rotation, k times
    for i in range(K):
        # take the last number off the end of the list
        last = A.pop()
        # put that number at the front
        A.insert(0,last)

    return A